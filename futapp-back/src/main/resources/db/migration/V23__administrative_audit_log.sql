CREATE TABLE auditoria_administrativa (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT,
    usuario VARCHAR(160),
    metodo VARCHAR(10) NOT NULL,
    ruta VARCHAR(500) NOT NULL,
    estado_http INTEGER NOT NULL,
    resultado VARCHAR(20) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    fecha TIMESTAMP NOT NULL
);

CREATE INDEX ix_auditoria_administrativa_fecha ON auditoria_administrativa (fecha DESC);
CREATE INDEX ix_auditoria_administrativa_usuario ON auditoria_administrativa (id_usuario, fecha DESC);
CREATE INDEX ix_auditoria_administrativa_request ON auditoria_administrativa (request_id);
