CREATE TABLE resultado_auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_partido BIGINT NOT NULL REFERENCES partido(id_partido) ON DELETE CASCADE,
    id_usuario BIGINT REFERENCES usuario(id_usuario) ON DELETE SET NULL,
    goles_local_anterior INTEGER,
    goles_visitante_anterior INTEGER,
    penales_local_anterior INTEGER,
    penales_visitante_anterior INTEGER,
    goles_local_nuevo INTEGER NOT NULL,
    goles_visitante_nuevo INTEGER NOT NULL,
    penales_local_nuevo INTEGER,
    penales_visitante_nuevo INTEGER,
    fecha_cambio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
