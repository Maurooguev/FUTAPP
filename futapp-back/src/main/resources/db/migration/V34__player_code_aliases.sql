CREATE TABLE jugador_alias (
    id_alias BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(11) NOT NULL UNIQUE,
    id_jugador BIGINT NOT NULL,
    CONSTRAINT fk_jugador_alias_jugador FOREIGN KEY (id_jugador) REFERENCES jugador(id_jugador)
);

CREATE INDEX ix_jugador_alias_jugador ON jugador_alias(id_jugador);
