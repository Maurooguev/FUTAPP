CREATE TABLE inscripcion_equipo (
    id_inscripcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo BIGINT NOT NULL,
    id_torneo BIGINT NOT NULL,
    categoria VARCHAR(120),
    estado VARCHAR(40) NOT NULL DEFAULT 'ACTIVA',
    fecha_alta DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_baja DATE,
    CONSTRAINT fk_inscripcion_equipo_club FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo),
    CONSTRAINT fk_inscripcion_equipo_torneo FOREIGN KEY (id_torneo) REFERENCES torneo (id_torneo),
    CONSTRAINT uk_inscripcion_equipo_torneo UNIQUE (id_equipo, id_torneo)
);

CREATE TABLE inscripcion_jugador (
    id_inscripcion_jugador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscripcion_equipo BIGINT NOT NULL,
    id_jugador BIGINT NOT NULL,
    numero_camiseta INTEGER,
    posicion VARCHAR(120),
    estado VARCHAR(40) NOT NULL DEFAULT 'ACTIVA',
    fecha_alta DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_baja DATE,
    CONSTRAINT fk_inscripcion_jugador_equipo FOREIGN KEY (id_inscripcion_equipo)
        REFERENCES inscripcion_equipo (id_inscripcion),
    CONSTRAINT fk_inscripcion_jugador_perfil FOREIGN KEY (id_jugador)
        REFERENCES jugador (id_jugador),
    CONSTRAINT uk_inscripcion_jugador UNIQUE (id_inscripcion_equipo, id_jugador),
    CONSTRAINT uk_inscripcion_camiseta UNIQUE (id_inscripcion_equipo, numero_camiseta),
    CONSTRAINT ck_inscripcion_camiseta CHECK (
        numero_camiseta IS NULL OR (numero_camiseta BETWEEN 1 AND 99)
    )
);

INSERT INTO inscripcion_equipo (id_equipo, id_torneo, estado)
SELECT id_equipo, id_torneo,
       CASE WHEN estado = 'INACTIVO' THEN 'INACTIVA' ELSE 'ACTIVA' END
FROM equipo;

INSERT INTO inscripcion_jugador (
    id_inscripcion_equipo, id_jugador, numero_camiseta, posicion, estado
)
SELECT ie.id_inscripcion, j.id_jugador, j.numero_camiseta, j.posicion,
       CASE WHEN j.estado = 'INACTIVO' THEN 'INACTIVA' ELSE 'ACTIVA' END
FROM jugador j
JOIN equipo e ON e.id_equipo = j.id_equipo
JOIN inscripcion_equipo ie
  ON ie.id_equipo = e.id_equipo AND ie.id_torneo = e.id_torneo;

CREATE INDEX ix_inscripcion_equipo_club ON inscripcion_equipo (id_equipo);
CREATE INDEX ix_inscripcion_equipo_torneo ON inscripcion_equipo (id_torneo);
CREATE INDEX ix_inscripcion_jugador_perfil ON inscripcion_jugador (id_jugador);
CREATE INDEX ix_inscripcion_jugador_equipo ON inscripcion_jugador (id_inscripcion_equipo);
