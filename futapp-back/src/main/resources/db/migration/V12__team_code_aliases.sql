CREATE TABLE equipo_alias (
    id_alias BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    id_equipo BIGINT NOT NULL,
    CONSTRAINT fk_equipo_alias_equipo FOREIGN KEY (id_equipo) REFERENCES equipo(id_equipo)
);

CREATE INDEX ix_equipo_alias_equipo ON equipo_alias(id_equipo);
