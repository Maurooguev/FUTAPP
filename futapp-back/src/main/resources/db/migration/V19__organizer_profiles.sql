CREATE TABLE perfil_organizador (
    id_perfil BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    nombre_publico VARCHAR(80) NOT NULL,
    descripcion VARCHAR(1200) NOT NULL,
    foto_perfil VARCHAR(500),
    foto_portada VARCHAR(500)
);
