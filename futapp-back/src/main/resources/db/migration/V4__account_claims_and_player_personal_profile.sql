CREATE TABLE equipo_administrador (
    id_equipo_administrador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,
    id_aprobado_por BIGINT,
    estado VARCHAR(40) NOT NULL DEFAULT 'ACTIVO',
    fecha_alta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_equipo_admin_equipo FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo),
    CONSTRAINT fk_equipo_admin_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_equipo_admin_aprobador FOREIGN KEY (id_aprobado_por) REFERENCES usuario (id_usuario),
    CONSTRAINT uk_equipo_administrador UNIQUE (id_equipo, id_usuario)
);

CREATE TABLE solicitud_reclamo (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    id_solicitante BIGINT NOT NULL,
    id_equipo BIGINT,
    id_jugador BIGINT,
    id_torneo BIGINT NOT NULL,
    id_revisor BIGINT,
    mensaje VARCHAR(500),
    motivo_resolucion VARCHAR(500),
    fecha_solicitud TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_resolucion TIMESTAMP,
    CONSTRAINT fk_reclamo_solicitante FOREIGN KEY (id_solicitante) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_reclamo_equipo FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo),
    CONSTRAINT fk_reclamo_jugador FOREIGN KEY (id_jugador) REFERENCES jugador (id_jugador),
    CONSTRAINT fk_reclamo_torneo FOREIGN KEY (id_torneo) REFERENCES torneo (id_torneo),
    CONSTRAINT fk_reclamo_revisor FOREIGN KEY (id_revisor) REFERENCES usuario (id_usuario),
    CONSTRAINT ck_reclamo_objetivo CHECK (
        (tipo = 'EQUIPO' AND id_equipo IS NOT NULL AND id_jugador IS NULL)
        OR (tipo = 'JUGADOR' AND id_jugador IS NOT NULL AND id_equipo IS NULL)
    )
);

