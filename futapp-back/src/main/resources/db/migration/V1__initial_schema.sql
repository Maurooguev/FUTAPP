CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(255) NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE torneo (
    id_torneo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    descripcion VARCHAR(255),
    ubicacion VARCHAR(255),
    estado VARCHAR(255),
    formato VARCHAR(255),
    cantidad_equipos INTEGER,
    codigo_publico VARCHAR(12),
    id_propietario BIGINT,
    CONSTRAINT uk_torneo_codigo_publico UNIQUE (codigo_publico),
    CONSTRAINT fk_torneo_propietario FOREIGN KEY (id_propietario) REFERENCES usuario (id_usuario)
);

CREATE TABLE equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    escudo VARCHAR(255),
    color_camiseta VARCHAR(255),
    barrio VARCHAR(255),
    responsable VARCHAR(255),
    telefono_contacto VARCHAR(255),
    estado VARCHAR(255),
    id_torneo BIGINT NOT NULL,
    CONSTRAINT fk_equipo_torneo FOREIGN KEY (id_torneo) REFERENCES torneo (id_torneo)
);

CREATE TABLE jugador (
    id_jugador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    apellido VARCHAR(255),
    dni VARCHAR(255),
    fecha_nacimiento VARCHAR(255),
    numero_camiseta INTEGER,
    posicion VARCHAR(255),
    foto VARCHAR(255),
    estado VARCHAR(255),
    id_equipo BIGINT NOT NULL,
    CONSTRAINT fk_jugador_equipo FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo),
    CONSTRAINT uk_jugador_equipo_camiseta UNIQUE (id_equipo, numero_camiseta)
);

CREATE UNIQUE INDEX uk_jugador_dni_informado
    ON jugador (dni)
    WHERE dni IS NOT NULL AND dni <> '';

CREATE TABLE fecha (
    id_fecha BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_fecha INTEGER,
    descripcion VARCHAR(255),
    estado VARCHAR(255),
    id_torneo BIGINT NOT NULL,
    CONSTRAINT fk_fecha_torneo FOREIGN KEY (id_torneo) REFERENCES torneo (id_torneo),
    CONSTRAINT uk_fecha_torneo_numero UNIQUE (id_torneo, numero_fecha)
);

CREATE TABLE partido (
    id_partido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora VARCHAR(255),
    estado VARCHAR(255),
    goles_local INTEGER DEFAULT 0,
    goles_visitante INTEGER DEFAULT 0,
    observaciones VARCHAR(255),
    id_torneo BIGINT NOT NULL,
    id_fecha BIGINT NOT NULL,
    id_equipo_local BIGINT NOT NULL,
    id_equipo_visitante BIGINT NOT NULL,
    CONSTRAINT fk_partido_torneo FOREIGN KEY (id_torneo) REFERENCES torneo (id_torneo),
    CONSTRAINT fk_partido_fecha FOREIGN KEY (id_fecha) REFERENCES fecha (id_fecha),
    CONSTRAINT fk_partido_local FOREIGN KEY (id_equipo_local) REFERENCES equipo (id_equipo),
    CONSTRAINT fk_partido_visitante FOREIGN KEY (id_equipo_visitante) REFERENCES equipo (id_equipo),
    CONSTRAINT ck_partido_equipos_distintos CHECK (id_equipo_local <> id_equipo_visitante),
    CONSTRAINT ck_partido_goles_validos CHECK (
        (goles_local IS NULL OR goles_local >= 0)
        AND (goles_visitante IS NULL OR goles_visitante >= 0)
    )
);

CREATE TABLE gol (
    id_gol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    minuto INTEGER,
    tipo_gol VARCHAR(255),
    observacion VARCHAR(255),
    id_partido BIGINT NOT NULL,
    id_jugador BIGINT NOT NULL,
    id_equipo BIGINT NOT NULL,
    CONSTRAINT fk_gol_partido FOREIGN KEY (id_partido) REFERENCES partido (id_partido),
    CONSTRAINT fk_gol_jugador FOREIGN KEY (id_jugador) REFERENCES jugador (id_jugador),
    CONSTRAINT fk_gol_equipo FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo)
);

CREATE TABLE tarjeta (
    id_tarjeta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_tarjeta VARCHAR(255),
    minuto INTEGER,
    motivo VARCHAR(255),
    id_partido BIGINT NOT NULL,
    id_jugador BIGINT NOT NULL,
    id_equipo BIGINT NOT NULL,
    CONSTRAINT fk_tarjeta_partido FOREIGN KEY (id_partido) REFERENCES partido (id_partido),
    CONSTRAINT fk_tarjeta_jugador FOREIGN KEY (id_jugador) REFERENCES jugador (id_jugador),
    CONSTRAINT fk_tarjeta_equipo FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo)
);

CREATE TABLE auth_token (
    token VARCHAR(64) PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_auth_token_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE INDEX ix_torneo_propietario ON torneo (id_propietario);
CREATE INDEX ix_equipo_torneo ON equipo (id_torneo);
CREATE INDEX ix_jugador_equipo ON jugador (id_equipo);
CREATE INDEX ix_fecha_torneo ON fecha (id_torneo);
CREATE INDEX ix_partido_torneo ON partido (id_torneo);
CREATE INDEX ix_partido_fecha ON partido (id_fecha);
CREATE INDEX ix_gol_partido ON gol (id_partido);
CREATE INDEX ix_tarjeta_partido ON tarjeta (id_partido);
CREATE INDEX ix_auth_token_usuario ON auth_token (id_usuario);
