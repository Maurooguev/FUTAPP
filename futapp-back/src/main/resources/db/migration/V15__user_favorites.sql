CREATE TABLE usuario_equipo_favorito (
    id_favorito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_equipo BIGINT NOT NULL REFERENCES equipo(id_equipo) ON DELETE CASCADE,
    fecha_alta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_equipo_favorito UNIQUE (id_usuario, id_equipo)
);

CREATE TABLE usuario_torneo_favorito (
    id_favorito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_torneo BIGINT NOT NULL REFERENCES torneo(id_torneo) ON DELETE CASCADE,
    fecha_alta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_torneo_favorito UNIQUE (id_usuario, id_torneo)
);

CREATE INDEX idx_favorito_equipo_usuario ON usuario_equipo_favorito(id_usuario);
CREATE INDEX idx_favorito_torneo_usuario ON usuario_torneo_favorito(id_usuario);
