CREATE TABLE competicion_division (
    id_division BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_torneo BIGINT NOT NULL REFERENCES torneo(id_torneo) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    orden INTEGER NOT NULL,
    CONSTRAINT uk_division_torneo_orden UNIQUE (id_torneo, orden)
);

CREATE TABLE competicion_fase (
    id_fase BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_division BIGINT NOT NULL REFERENCES competicion_division(id_division) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    orden INTEGER NOT NULL,
    clasificados INTEGER,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT uk_fase_division_orden UNIQUE (id_division, orden)
);

CREATE TABLE competicion_zona (
    id_zona BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fase BIGINT NOT NULL REFERENCES competicion_fase(id_fase) ON DELETE CASCADE,
    nombre VARCHAR(60) NOT NULL,
    orden INTEGER NOT NULL,
    CONSTRAINT uk_zona_fase_orden UNIQUE (id_fase, orden)
);

CREATE TABLE cupo_equipo (
    id_cupo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_division BIGINT NOT NULL REFERENCES competicion_division(id_division) ON DELETE CASCADE,
    id_zona BIGINT REFERENCES competicion_zona(id_zona) ON DELETE SET NULL,
    id_equipo BIGINT REFERENCES equipo(id_equipo) ON DELETE SET NULL,
    numero INTEGER NOT NULL,
    etiqueta VARCHAR(80) NOT NULL,
    CONSTRAINT uk_cupo_division_numero UNIQUE (id_division, numero),
    CONSTRAINT uk_cupo_division_equipo UNIQUE (id_division, id_equipo)
);

-- Los torneos existentes reciben una estructura mínima compatible.
INSERT INTO competicion_division (id_torneo, nombre, orden)
SELECT id_torneo, 'División única', 1 FROM torneo;

INSERT INTO competicion_fase (id_division, nombre, tipo, orden, estado)
SELECT d.id_division, 'Liga', 'LIGA', 1, 'PENDIENTE'
FROM competicion_division d;
