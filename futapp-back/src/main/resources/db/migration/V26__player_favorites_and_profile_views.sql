CREATE TABLE usuario_jugador_favorito (
    id_favorito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_jugador BIGINT NOT NULL REFERENCES jugador(id_jugador) ON DELETE CASCADE,
    fecha_alta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_jugador_favorito UNIQUE (id_usuario, id_jugador)
);

CREATE INDEX idx_favorito_jugador_usuario ON usuario_jugador_favorito(id_usuario);

